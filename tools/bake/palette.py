def category(kind, h, a_m2):
    """Тип застройки. kind — класс из OSM (0 — просто building=yes, таких ~96%)."""
    if kind == 5: return "mosque"
    if kind == 7: return "minaret"
    if kind == 8: return "church"
    if kind == 9: return "garage"
    if kind == 4: return "industry"
    if kind == 6: return "public"
    if h >= 40: return "tower"
    if kind == 3: return "shop"
    if kind == 2: return "apt"
    if kind == 1: return "house"
    # kind 0: угадываем по высоте и площади
    if a_m2 >= 2500 and h <= 12: return "industry"
    if h <= 7.5 or (h <= 10 and a_m2 < 400): return "house"
    return "apt"


def _mix(seed):
    seed = (seed * 2654435761 + 0x9E3779B9) & 0xffffffff
    seed ^= seed >> 15; seed = (seed * 2246822519) & 0xffffffff; seed ^= seed >> 13
    return seed


def _pick(pal, seed):
    tot = sum(p[3] for p in pal)
    r = (_mix(seed) % 10000) / 10000 * tot
    for p in pal:
        r -= p[3]
        if r < 0: return p[:3]
    return pal[-1][:3]


def _jitter(c, seed, amt):
    s = _mix(seed ^ 0x5bd1e995)
    k = 1 + ((s & 255) / 255 - 0.5) * amt  # общая яркость
    out = []
    for i, v in enumerate(c):
        d = ((s >> (8 + i * 6)) & 63) / 63 - 0.5  # лёгкий сдвиг оттенка
        out.append(max(0, min(255, int(round(v * k + d * 8)))))
    return (out[0] << 16) | (out[1] << 8) | out[2]


def wall_color(kind, h, a_m2, seed):
    cat = category(kind, h, a_m2)
    return _jitter(_pick(WALL[cat], seed), seed, 0.08)


def roof_color(kind, roof, h, a_m2, seed):
    s = seed ^ 0x27d4eb2f
    if roof in (4, 5): return _jitter(_pick(DOME, s), s, 0.06)
    cat = category(kind, h, a_m2)
    if roof:  # скатная
        return _jitter(_pick(ROOF_PITCH, s), s, 0.1)
    key = cat if cat in ROOF_FLAT else "big" if cat in ("industry", "shop", "garage") else "public" if cat in ("mosque", "minaret", "church") else "apt"
    if cat == "shop" or (cat == "apt" and a_m2 >= 2500): key = "big"
    return _jitter(_pick(ROOF_FLAT[key], s), s, 0.08)
